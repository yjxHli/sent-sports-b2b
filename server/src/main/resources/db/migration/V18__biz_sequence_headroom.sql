-- V18：为业务单号序列预留高位空间
-- 背景：演示数据生成器自建单号（DEMO-* / SO+yyyyMMdd+6 位）已占用 000001~006907；
--       V17 把持久化序列从 1000 起跳，正好落在该区间内，导致新建单号与历史演示订单撞号
--       （下单命中了历史订单 → 支付金额校验 40001）。
--       这里把序列抬到 900000，与演示数据彻底隔离（6 位序列上限 999999，剩余 10 万号）。
UPDATE sys_sequence
SET seq_value = 900000
WHERE seq_name = 'BIZ_NO' AND seq_value < 900000;
