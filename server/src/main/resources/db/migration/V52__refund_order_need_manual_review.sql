-- V52：定制退款三档处置 —— 退款单「需人工复核」标记（2026-11-21 用户口径）
-- APPROVED（审核通过未排产）不是不能退，但图纸已过审、可能已备料打样，
-- 必须让客服在审核台看见并确认，因此把申请时刻的判定结果快照下来。
--
-- 为什么落库快照而不是列表时按 custom_order 现算：定制单可能在用户提交退款之后
-- 才被工厂排产；现算会让这条标记凭空消失，客服就看不到「它当初为什么需要复核」。
-- 存量退款单全部为普通申请，默认 0。
-- ============================================================================
ALTER TABLE refund_order
    ADD COLUMN need_manual_review TINYINT NOT NULL DEFAULT 0
        COMMENT '是否需客服人工复核：1=定制单审核通过未排产（APPROVED/ESCALATED）';
