-- 背景：结算页「使用积分抵扣」的上限 = min(可用积分, 商品额 × 30%)。
-- 演示账号 9002（13800138000）原余额为 0，E2E 与人工验收永远看不到 30% 封顶生效，
-- 所以把余额提到 50000（= 500 元可抵）：任何一次普通下单都会先撞「商品额 30%」的天花板，
