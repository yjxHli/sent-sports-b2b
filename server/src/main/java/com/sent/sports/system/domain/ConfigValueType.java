package com.sent.sports.system.domain;

/**
 * 配置项取值类型（系统配置中心，2026-11-25）。
 *
 * <p>只列管理端真正用得到的几种：类型决定「弹窗给什么控件」与「写库前怎么校验」，
 * 不要为了通用性堆一串没人用的类型——多一种就多一处校验分支要维护。</p>
 */
public enum ConfigValueType {

    /** 非负整数（分钟 / 天数 / 件数都走这个，单位由字典里的 unit 描述）。 */
    NUMBER,
    /** 金额，单位固定为「分」（与全库金额口径一致，避免 12.34 元这种浮点进库）。 */
    MONEY_CENT,
    /** 百分比，0~100 的整数。 */
    PERCENT,
    /** 布尔开关，落库 {@code true} / {@code false}。 */
    BOOLEAN,
    /** 自由文本：字典里没有的键一律按这个处理。 */
    TEXT
}
